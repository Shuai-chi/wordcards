interface CryptoCapabilities {
  randomUUID?: () => string;
  getRandomValues?: (target: Uint8Array) => Uint8Array;
  subtle?: {
    digest: (algorithm: string, data: BufferSource) => Promise<ArrayBuffer>;
  };
}

